// Packs the SvelteKit static output (build/) into one ES-module Cloudflare Worker (dist/worker.js).
// Node only. Run after `vite build` (npm run build does both).
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { brotliCompressSync, gzipSync } from "node:zlib";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const TYPES = {
  ".html": "text/html; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".svg": "image/svg+xml",
  ".png": "image/png",
  ".webp": "image/webp",
  ".txt": "text/plain; charset=utf-8",
  ".xml": "application/xml; charset=utf-8",
  ".json": "application/json",
};
const IMMUTABLE = "public, max-age=31536000, immutable";
const SHORT = "public, max-age=300, must-revalidate";
// no-transform stops Cloudflare rewriting HTML (e.g. auto-injected Web Analytics beacon).
const HTML = "public, max-age=300, must-revalidate, no-transform";
const MEDIUM = "public, max-age=3600, must-revalidate";
const hash = (b) => createHash("sha256").update(b).digest("hex").slice(0, 12);

function walk(dir) {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const baseCsp = (styleSrc) =>
  [
    "default-src 'none'",
    `style-src ${styleSrc}`,
    "img-src 'self' data:",
    "connect-src 'self'",
    "base-uri 'none'",
    "form-action 'none'",
    "frame-ancestors 'none'",
    "upgrade-insecure-requests",
  ].join("; ");

export function pack({ siteDir = join(ROOT, "build"), outDir = join(ROOT, "dist") } = {}) {
  const cfg = JSON.parse(readFileSync(join(ROOT, "site.config.json"), "utf8"));
  const table = {};
  const sizes = {}; // informational only: Cloudflare compresses at the edge, the worker never does

  for (const file of walk(siteDir)) {
    const rel = "/" + relative(siteDir, file).split("\\").join("/");
    const ext = rel.slice(rel.lastIndexOf("."));
    const type = TYPES[ext];
    if (!type) throw new Error(`unknown file type: ${rel}`);
    let buf = readFileSync(file);
    let path = rel;
    let status;
    let hidden;
    let csp = baseCsp("'none'");

    if (ext === ".html") {
      let html = buf.toString("utf8");
      // csr=false: SvelteKit still emits a disabled preload link to the stylesheet that is already inlined. Drop it.
      html = html.replace(/<link\b[^>]*rel="stylesheet"[^>]*>/g, "").replace(/\/\*![\s\S]*?\*\//g, ""); // also the tailwind banner
      if (/<script\b/i.test(html)) throw new Error(`${rel}: unexpected <script>; the site must ship no JavaScript`);
      if (/\sstyle=/i.test(html)) throw new Error(`${rel}: inline style attribute would violate the CSP`);
      const hashes = [...html.matchAll(/<style\b[^>]*>([\s\S]*?)<\/style>/g)].map(
        (m) => `'sha256-${createHash("sha256").update(m[1]).digest("base64")}'`,
      );
      csp = baseCsp(hashes.length ? hashes.join(" ") : "'none'");
      buf = Buffer.from(html);
      path = rel === "/index.html" ? "/" : rel.replace(/\.html$/, "");
      if (path === "/404") { status = 404; hidden = true; }
    } else if (rel.endsWith(".css") && rel.includes("/_app/")) {
      continue; // inlined into every page, never requested
    }

    const cache = rel.startsWith("/_app/immutable/") ? IMMUTABLE : ext === ".html" ? HTML : ext === ".txt" || ext === ".xml" ? SHORT : MEDIUM;
    const text = /^(text|application\/xml|image\/svg)/.test(type);
    table[path] = {
      type, cache, csp, status, hidden,
      etag: `"${hash(buf)}"`,
      text,
      body: text ? buf.toString("utf8") : buf.toString("base64"),
    };
    sizes[path] = { raw: buf.length, gzip: gzipSync(buf, { level: 9 }).length, br: brotliCompressSync(buf).length };
  }
  if (!table["/"] || !table["/404"] || !table["/privacy"]) throw new Error("missing page in build output");
  if (table["/favicon-48.png"]) table["/favicon.ico"] = { ...table["/favicon-48.png"] };

  const security = {
    "X-Content-Type-Options": "nosniff",
    "Referrer-Policy": "no-referrer",
    "Permissions-Policy": "accelerometer=(), camera=(), geolocation=(), gyroscope=(), microphone=(), payment=(), usb=(), interest-cohort=()",
    "Strict-Transport-Security": "max-age=31536000; includeSubDomains",
    "Cross-Origin-Opener-Policy": "same-origin",
    "X-Frame-Options": "DENY",
  };

  const worker = `// Generated by scripts/build.mjs from the SvelteKit static output. Do not edit.
const ASSETS = ${JSON.stringify(table)};
const SECURITY = ${JSON.stringify(security)};
const REDIRECTS = { "/index.html": "/", "/privacy/": "/privacy", "/privacy.html": "/privacy" };

const bin = new Map();
function payload(a) {
  if (a.text) return a.body;
  let b = bin.get(a);
  if (!b) {
    const s = atob(a.body);
    b = new Uint8Array(s.length);
    for (let i = 0; i < s.length; i++) b[i] = s.charCodeAt(i);
    bin.set(a, b);
  }
  return b;
}

// Always the plain body, never Content-Encoding: Cloudflare compresses text at the edge.
function respond(a, request, status, extra = {}) {
  const h = new Headers({
    "Content-Type": a.type,
    "Cache-Control": a.cache,
    ETag: a.etag,
    "Content-Security-Policy": a.csp,
    ...SECURITY,
    ...extra,
  });
  const inm = request.headers.get("If-None-Match");
  if (status === 200 && inm && inm.split(",").some((t) => t.trim().replace(/^W\\//, "") === a.etag)) {
    h.delete("Content-Type");
    return new Response(null, { status: 304, headers: h });
  }
  return new Response(request.method === "HEAD" ? null : payload(a), { status, headers: h });
}

export default {
  async fetch(request) {
    const method = request.method;
    if (method !== "GET" && method !== "HEAD") {
      return new Response("Method Not Allowed", { status: 405, headers: { Allow: "GET, HEAD", ...SECURITY } });
    }
    const path = new URL(request.url).pathname;
    if (REDIRECTS[path]) {
      return new Response(null, { status: 301, headers: { Location: REDIRECTS[path], "Cache-Control": "public, max-age=3600", ...SECURITY } });
    }
    const a = Object.hasOwn(ASSETS, path) ? ASSETS[path] : undefined;
    if (!a || a.hidden) {
      return respond(ASSETS["/404"], request, 404, { "Cache-Control": "public, max-age=60, no-transform", "X-Robots-Tag": "noindex" });
    }
    return respond(a, request, a.status || 200);
  },
};
`;
  mkdirSync(outDir, { recursive: true });
  writeFileSync(join(outDir, "worker.js"), worker);
  writeFileSync(
    join(outDir, "metadata.json"),
    JSON.stringify({ name: "nocturne-website", main_module: "worker.js", compatibility_date: "2025-01-01", compatibility_flags: [], released: cfg.RELEASED === true }, null, 2) + "\n",
  );
  return { worker, bytes: Buffer.byteLength(worker), table, sizes, outDir };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const r = pack({ siteDir: process.env.SITE_OUT ? resolve(process.env.SITE_OUT) : undefined });
  console.log(`dist/worker.js ${(r.bytes / 1024).toFixed(1)} KiB, ${Object.keys(r.table).length} routes/assets`);
}
